"""Generate documentation tables from saved evidence without hand copying."""

from __future__ import annotations

import json
from pathlib import Path
from statistics import mean, median


def row(*values):
    """Render one Markdown table row."""
    return "| " + " | ".join(str(value) for value in values) + " |"


def main():
    """Regenerate the included Markdown tables from benchmark JSON artifacts."""
    quality = json.loads(Path("benchmarks/results/quality.json").read_text())
    resources = json.loads(Path("benchmarks/results/resources.json").read_text())
    electricity = quality["electricity"]
    lines = [
        "<!-- Generated by python -m benchmarks.render -->",
        "",
        "## Chronological Elec2 results",
        "",
        row(
            "Method",
            "Brier",
            "Array bytes",
            "Serialized bytes",
            "p95 predict ms",
            "p95 update ms",
        ),
        "|---|---:|---:|---:|---:|---:|",
    ]
    lines.extend(
        row(
            r["name"],
            f"{r['brier']:.4f}",
            f"{r['state_bytes']:,}",
            f"{r['serialized_bytes']:,}",
            f"{r['p95_predict_ms']:.3f}",
            f"{r['p95_update_ms']:.3f}",
        )
        for r in electricity["test"]
    )
    lines += [
        "",
        "Times measure calls on batches of up to 336 observations.",
        "Array bytes include upstream fitted models. Python scalar state",
        "is reflected in serialized size. Serialization is not process memory.",
        "",
        row("Reference", "Brier difference", "Paired 95% interval"),
        "|---|---:|---:|",
    ]
    lines.extend(
        row(name, f"{delta:.4f}", f"[{lower:.4f}, {upper:.4f}]")
        for name, (delta, lower, upper) in electricity["paired_brier_intervals"].items()
    )
    lines += [
        "",
        "Differences are streamcal minus reference. Intervals are marginal,",
        "not simultaneous across methods. Crossing zero establishes neither",
        "superiority nor equivalence.",
        "",
        "## Constrained validation choices",
        "",
        "Every row requires p95 prediction calls <=100 ms. Update budgets also",
        "apply to p95 calls. Choices use validation data. The final column",
        "checks the budgets again on test.",
        "",
        row(
            "Objective",
            "Update budget ms",
            "State budget bytes",
            "Choice",
            "Test objective",
            "Test budget met",
        ),
        "|---|---:|---:|---|---:|---|",
    ]
    for point in electricity["operating_points"]:
        score = (
            "N/A"
            if point["test"] is None
            else (f"{point['test'][point['objective']]:.4f}")
        )
        lines.append(
            row(
                point["objective"],
                point["max_update_ms"],
                f"{point['max_serialized_bytes']:,}",
                point["selected"] or "No feasible choice",
                score,
                point["test_resource_feasible"],
            )
        )
    lines += [
        "",
        "## Controlled expected-result experiments",
        "",
        "Mean squared distance to the known conditional probability over three",
        "seeds. Lower is better. Settings are fixed across scenarios. Sparse",
        "cases reveal one in ten labels; delayed cases reveal them 0-399 events",
        "later. No settings are chosen from these displayed results.",
        "",
        row("Scenario", "Raw", "Streamcal", "Rolling isotonic", "Online logistic"),
        "|---|---:|---:|---:|---:|",
    ]
    for scenario in (
        "calibrated",
        "stationary",
        "abrupt",
        "gradual",
        "sparse",
        "delayed",
    ):
        values = [
            mean(
                r["known_truth_mse"]
                for r in quality["controlled"]
                if r["scenario"] == scenario and r["name"] == name
            )
            for name in ("raw", "stream", "rolling-isotonic", "online-logistic")
        ]
        lines.append(row(scenario, *(f"{v:.5f}" for v in values)))
    lines += [
        "",
        "## Isolated resource measurements",
        "",
        "Medians of two fresh processes: 10,000 observations, batches of 100.",
        "Rolling and accumulating references refit every 16 batches here.",
        "",
        row(
            "Method",
            "Arrays bytes",
            "Serialized bytes",
            "Peak process MiB",
            "p95 predict ms",
            "p95 update ms",
        ),
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for method in ("stream", "rolling", "accumulating", "online-logistic"):
        rows = [
            r
            for r in resources["measurements"]
            if r["method"] == method
            and r["observations"] == 10000
            and r["batch_size"] == 100
        ]
        values = {
            key: median(r[key] for r in rows)
            for key in (
                "numeric_array_bytes",
                "serialized_bytes",
                "peak_process_rss_bytes",
                "p95_predict_call_ms",
                "p95_update_call_ms",
            )
        }
        lines.append(
            row(
                method,
                f"{values['numeric_array_bytes']:.0f}",
                f"{values['serialized_bytes']:.0f}",
                f"{values['peak_process_rss_bytes'] / 2**20:.1f}",
                f"{values['p95_predict_call_ms']:.3f}",
                f"{values['p95_update_call_ms']:.3f}",
            )
        )
    lines += [
        "",
        "Peak RSS includes interpreter, common imports, model and temporaries.",
        "The JSON also records baseline RSS, single-event calls, batches of",
        "1,000, stream lengths 1,000 and 10,000, and 100,000-observation runs",
        "with batches of 1,000.",
        "",
        "## Provenance",
        "",
        f"Python {quality['environment']['python']}.",
        quality["environment"]["platform"],
        "",
        f"Quality source SHA-256: `{quality['environment']['source_sha256']}`.",
        "",
        f"Resource source SHA-256: `{resources['environment']['source_sha256']}`.",
        "",
    ]
    Path("docs/evidence-results.md").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
